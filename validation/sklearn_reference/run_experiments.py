"""T16 experiment orchestrator: NMFlib (MoonBit) vs scikit-learn reference.

Pipeline:
  1. load fixed datasets (generate_data.py, regenerated if missing);
  2. build the case grid (3 valid combos x 4 regularization configs x
     5 seeds x Random init, plus a deterministic NNDSVD/NNDSVDa layer);
  3. generate MoonBit case literals and run the independent runner module
     (`moon run --target native`, public API only);
  4. fit sklearn with mapped parameters for every case;
  5. re-evaluate BOTH sides' final W/H with the independent objective.py;
  6. write results/results.csv + results/metadata.json.

Failures are recorded per case (status=error) and reported loudly; nothing
is silently skipped. A runner/toolchain failure aborts with a non-zero exit.

Usage:
  python run_experiments.py            # full grid
  python run_experiments.py --smoke    # tiny CI smoke subset
"""

from __future__ import annotations

import argparse
import csv
import json
import math
import subprocess
import sys
import time
from pathlib import Path

import numpy as np

import generate_data
import nmf_reference
import objective

HERE = Path(__file__).parent
RUNNER = HERE / "moonbit_runner"

COMBOS = [("MU", "frobenius"), ("CD", "frobenius"), ("MU", "kl")]
REG_CONFIGS = [
    ("none", 0.0, 0.0),
    ("l1", 0.05, 0.0),
    ("l2", 0.0, 0.1),
    ("l1l2", 0.05, 0.1),
]
SEEDS = [11, 23, 42, 77, 101]
DET_INITS = ["NNDSVD", "NNDSVDa"]
MAX_ITER = 500
TOL = 1e-6

RESULT_FIELDS = [
    "run_id", "impl", "dataset", "shape", "rank", "solver", "loss",
    "reg_name", "l1_reg", "l2_reg", "alpha_W", "alpha_H", "l1_ratio",
    "init", "seed", "max_iter", "tol", "status", "error",
    "n_iter", "converged", "hit_max_iter", "fit_seconds",
    "reconstruction_error", "data_loss", "regularization_penalty",
    "full_objective", "objective_status",
    "reported_loss_value", "reported_reconstruction_err",
    "crosscheck_rel_diff", "crosscheck_abs_diff",
    "w_finite", "h_finite", "wh_finite", "w_nonneg", "h_nonneg", "wh_nonneg",
    "w_nnzs", "h_nnzs",
]


def case_id(ds, solver, loss, reg, init, seed):
    return f"{ds}|{solver}|{loss}|{reg}|{init}|{seed}"


def build_cases(datasets, smoke: bool):
    names = ["A1"] if smoke else list(datasets)
    regs = REG_CONFIGS[:1] if smoke else REG_CONFIGS
    seeds = [42] if smoke else SEEDS
    cases = []
    for ds in names:
        for solver, loss in COMBOS:
            for reg, l1, l2 in regs:
                for seed in seeds:
                    cases.append(dict(
                        dataset=ds, solver=solver, loss=loss, reg_name=reg,
                        l1_reg=l1, l2_reg=l2, init="Random", seed=seed,
                    ))
    if not smoke:
        for ds in names:
            for solver, loss in COMBOS:
                for reg, l1, l2 in regs:
                    for init in DET_INITS:
                        cases.append(dict(
                            dataset=ds, solver=solver, loss=loss,
                            reg_name=reg, l1_reg=l1, l2_reg=l2,
                            init=init, seed=42,
                        ))
    for c in cases:
        c["id"] = case_id(
            c["dataset"], c["solver"], c["loss"], c["reg_name"],
            c["init"], c["seed"],
        )
        c["k"] = datasets[c["dataset"]]["k"]
    return cases


def load_datasets(data_dir: Path):
    meta_path = data_dir / "metadata.json"
    if not meta_path.exists():
        print("data/ missing -> generating fixed datasets", flush=True)
        sys.argv = ["generate_data.py", "--out", str(data_dir)]
        generate_data.main()
    meta = json.loads(meta_path.read_text(encoding="utf-8"))
    datasets = {}
    for name in meta:
        with np.load(data_dir / f"{name}.npz") as z:
            datasets[name] = dict(meta[name])
            datasets[name]["v"] = z["v"]
    return datasets


def mbx_literal(x: float) -> str:
    # Python repr round-trips float64; normalize to MoonBit literal syntax
    # (decimal point required, exponent without leading zeros).
    s = repr(float(x))
    if "e" in s or "E" in s:
        mant, exp = s.lower().split("e")
        if "." not in mant:
            mant += ".0"
        return f"{mant}e{int(exp)}"
    if "." not in s:
        s += ".0"
    return s


def generate_moonbit_cases(cases, datasets, path: Path):
    lines = ["// Generated by run_experiments.py. Do not edit.", ""]
    for name, d in datasets.items():
        v = d["v"]
        flat = ", ".join(mbx_literal(x) for x in v.ravel())
        lines.append(
            f"let v_{name.lower()} : @nmf.Matrix = "
            f"mat({v.shape[0]}, {v.shape[1]}, [{flat}])"
        )
    lines.append("")
    lines.append("let t16_cases : Array[T16Case] = [")
    solver_map = {"MU": "@nmf.Solver::MU", "CD": "@nmf.Solver::CD"}
    loss_map = {
        "frobenius": "@nmf.Loss::Frobenius",
        "kl": "@nmf.Loss::KLDivergence",
    }
    init_map = {
        "Random": "@nmf.Init::Random",
        "NNDSVD": "@nmf.Init::NNDSVD",
        "NNDSVDa": "@nmf.Init::NNDSVDa",
    }
    for c in cases:
        lines.append(
            "  { id: \"" + c["id"] + "\", v: v_" + c["dataset"].lower()
            + f", k: {c['k']}, solver: {solver_map[c['solver']]}"
            + f", loss: {loss_map[c['loss']]}, init: {init_map[c['init']]}"
            + f", max_iter: {MAX_ITER}, tol: {mbx_literal(TOL)}"
            + f", seed: {c['seed']}UL, l1: {mbx_literal(c['l1_reg'])}"
            + f", l2: {mbx_literal(c['l2_reg'])}" + " },"
        )
    lines.append("]")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def run_moonbit(cases, datasets):
    generate_moonbit_cases(cases, datasets, RUNNER / "cases_gen.mbt")
    t0 = time.perf_counter()
    proc = subprocess.run(
        ["moon", "run", "--target", "native", "."],
        cwd=RUNNER, capture_output=True, text=True,
        encoding="utf-8", errors="replace", shell=True,
    )
    wall = time.perf_counter() - t0
    if proc.returncode != 0:
        print("MoonBit runner FAILED:", file=sys.stderr)
        print(proc.stderr, file=sys.stderr)
        sys.exit(1)
    results = {}
    for line in proc.stdout.splitlines():
        if not line.strip():
            continue
        parts = line.split(",", 2)
        cid, status = parts[0], parts[1]
        if status == "ok":
            f = line.split(",")
            w = np.array(
                [float(x) for x in f[10:10 + int(f[6]) * int(f[7])]]
            ).reshape(int(f[6]), int(f[7]))
            h = np.array([float(x) for x in f[10 + w.size:]]).reshape(
                int(f[8]), int(f[9])
            )
            results[cid] = dict(
                status="ok", n_iter=int(f[2]), converged=f[3] == "true",
                loss_value=float(f[4]), recon=float(f[5]), w=w, h=h,
            )
        else:
            results[cid] = dict(status="error", error=parts[2])
    missing = [c["id"] for c in cases if c["id"] not in results]
    if missing:
        print(f"FATAL: runner produced no output for {len(missing)} cases: "
              f"{missing[:5]}...", file=sys.stderr)
        sys.exit(1)
    return results, wall


def independent_metrics(v, w, h, loss, l1, l2):
    """Re-evaluate final factors with objective.py; never trust library loss."""
    out = {}
    health = objective.factor_health(w, h)
    out.update(health)
    wh = w @ h
    out["reconstruction_error"] = objective.reconstruction_error(v, wh)
    out["regularization_penalty"] = objective.regularization_penalty(w, h, l1, l2)
    try:
        dl = objective.data_loss(v, wh, loss)
        out["data_loss"] = dl
        out["full_objective"] = dl + out["regularization_penalty"]
        out["objective_status"] = "ok"
    except objective.KLInfiniteError as e:
        out["data_loss"] = ""
        out["full_objective"] = ""
        out["objective_status"] = f"kl_infinite: {e}"
    return out


def base_row(c, impl, datasets):
    v = datasets[c["dataset"]]["v"]
    m, n = v.shape
    reg = nmf_reference.map_regularization(c["l1_reg"], c["l2_reg"], m, n)
    return {
        "run_id": c["id"], "impl": impl, "dataset": c["dataset"],
        "shape": f"{m}x{n}", "rank": c["k"], "solver": c["solver"],
        "loss": c["loss"], "reg_name": c["reg_name"],
        "l1_reg": c["l1_reg"], "l2_reg": c["l2_reg"],
        "alpha_W": reg["alpha_W"], "alpha_H": reg["alpha_H"],
        "l1_ratio": reg["l1_ratio"],
        "init": c["init"], "seed": c["seed"],
        "max_iter": MAX_ITER, "tol": TOL,
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--smoke", action="store_true")
    ap.add_argument("--data", default=str(HERE / "data"))
    ap.add_argument("--out", default=str(HERE / "results"))
    args = ap.parse_args()
    data_dir, out_dir = Path(args.data), Path(args.out)
    out_dir.mkdir(parents=True, exist_ok=True)

    datasets = load_datasets(data_dir)
    cases = build_cases(datasets, args.smoke)
    print(f"cases per implementation: {len(cases)} "
          f"({'smoke' if args.smoke else 'full grid'})", flush=True)

    mb_results, mb_wall = run_moonbit(cases, datasets)
    print(f"MoonBit runner finished in {mb_wall:.2f}s", flush=True)

    rows = []
    for c in cases:
        v = datasets[c["dataset"]]["v"]

        # --- NMFlib side (independent re-evaluation of runner W/H) ---
        row = base_row(c, "nmflib", datasets)
        r = mb_results[c["id"]]
        if r["status"] == "ok":
            row.update(status="ok", error="", n_iter=r["n_iter"],
                       converged=r["converged"],
                       hit_max_iter=r["n_iter"] >= MAX_ITER,
                       fit_seconds="",  # no per-fit timing via public API
                       reported_loss_value=r["loss_value"],
                       reported_reconstruction_err=r["recon"])
            met = independent_metrics(
                v, r["w"], r["h"], c["loss"], c["l1_reg"], c["l2_reg"])
            row.update(met)
            if met["objective_status"] == "ok":
                abs_diff = abs(r["loss_value"] - met["full_objective"])
                denom = max(abs(met["full_objective"]), 1e-300)
                row["crosscheck_abs_diff"] = abs_diff
                row["crosscheck_rel_diff"] = abs_diff / denom
            else:
                row["crosscheck_rel_diff"] = ""
                row["crosscheck_abs_diff"] = ""
        else:
            row.update(status="error", error=r["error"], n_iter="",
                       converged="", hit_max_iter="", fit_seconds="",
                       reported_loss_value="", reported_reconstruction_err="",
                       crosscheck_rel_diff="", crosscheck_abs_diff="",
                       objective_status="not_evaluated")
        rows.append(row)

        # --- sklearn side ---
        row = base_row(c, "sklearn", datasets)
        try:
            r = nmf_reference.fit_sklearn(
                v, c["k"], c["solver"], c["loss"], c["init"], c["seed"],
                c["l1_reg"], c["l2_reg"], MAX_ITER, TOL,
            )
            row.update(status="ok", error="", n_iter=r["n_iter"],
                       converged="",  # sklearn NMF has no converged field
                       hit_max_iter=r["hit_max_iter"],
                       fit_seconds=r["fit_seconds"],
                       reported_loss_value="",
                       reported_reconstruction_err=r["reported_reconstruction_err"])
            met = independent_metrics(
                v, r["w"], r["h"], c["loss"], c["l1_reg"], c["l2_reg"])
            row.update(met)
            if met["objective_status"] == "ok":
                # sklearn reconstruction_err_ is sqrt(beta-divergence):
                # Frobenius norm for frobenius loss, sqrt(2*KL) for KL loss.
                if c["loss"] == "kl":
                    expected = math.sqrt(2.0 * met["data_loss"])
                else:
                    expected = met["reconstruction_error"]
                denom = max(abs(expected), 1e-300)
                abs_diff = abs(r["reported_reconstruction_err"] - expected)
                row["crosscheck_abs_diff"] = abs_diff
                row["crosscheck_rel_diff"] = abs_diff / denom
            else:
                row["crosscheck_rel_diff"] = ""
                row["crosscheck_abs_diff"] = ""
        except Exception as e:  # recorded, never silently skipped
            row.update(status="error", error=f"{type(e).__name__}: {e}",
                       n_iter="", converged="", hit_max_iter="",
                       fit_seconds="", reported_loss_value="",
                       reported_reconstruction_err="",
                       crosscheck_rel_diff="", crosscheck_abs_diff="",
                       objective_status="not_evaluated")
        rows.append(row)

    csv_path = out_dir / ("results_smoke.csv" if args.smoke else "results.csv")
    with csv_path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=RESULT_FIELDS, extrasaction="ignore")
        writer.writeheader()
        for row in rows:
            writer.writerow(row)

    errors = [r for r in rows if r["status"] == "error"]
    kl_inf = [r for r in rows if str(r.get("objective_status", "")).startswith("kl_infinite")]
    cross = [float(r["crosscheck_rel_diff"]) for r in rows
             if r.get("crosscheck_rel_diff") not in ("", None)]
    cross_abs = [float(r["crosscheck_abs_diff"]) for r in rows
                 if r.get("crosscheck_abs_diff") not in ("", None)]
    # Dual threshold: near-zero objectives (e.g. exact recovery of the
    # rank-deficient dataset C) are dominated by summation cancellation, so
    # a relative-only check misfires there. Verified against math.fsum:
    # absolute discrepancies are <= ~4e-14, far below the 1e-9 abs bound.
    cross_fail = [
        r["run_id"] for r in rows
        if r.get("crosscheck_rel_diff") not in ("", None)
        and float(r["crosscheck_rel_diff"]) > 1e-8
        and float(r["crosscheck_abs_diff"]) > 1e-9
    ]
    meta = {
        "task": "T16 sklearn reference validation",
        "mode": "smoke" if args.smoke else "full",
        "environment": nmf_reference.environment_info(),
        "grid": {
            "datasets": {n: {k: d[k] for k in ("shape", "k", "true_rank",
                                               "numeric_rank", "seed",
                                               "zero_fraction")}
                         for n, d in datasets.items()},
            "combos": COMBOS, "reg_configs": REG_CONFIGS, "seeds": SEEDS,
            "deterministic_inits": DET_INITS,
            "max_iter": MAX_ITER, "tol": TOL,
            "cases_per_impl": len(cases),
        },
        "semantic_differences": nmf_reference.SEMANTIC_DIFFERENCES,
        "moonbit_runner_wall_seconds": mb_wall,
        "nmflib_fit_seconds_note": (
            "per-fit timing is not exposed by the NMFlib public API; only the "
            "total runner wall time is recorded (no production change made)"
        ),
        "reproducibility_note": (
            "verified empirically with two consecutive full-grid runs: all "
            "results.csv columns are bit-identical except fit_seconds (sklearn "
            "per-fit wall timings) and moonbit_runner_wall_seconds here, which "
            "are inherently nondeterministic; datasets, parameters, factors, "
            "objectives and crosschecks reproduce exactly"
        ),
        "crosscheck_max_rel_diff": max(cross) if cross else None,
        "crosscheck_max_abs_diff": max(cross_abs) if cross_abs else None,
        "crosscheck_rule": "fail if rel > 1e-8 AND abs > 1e-9 (cancellation near zero)",
        "error_runs": [
            {"run_id": r["run_id"], "impl": r["impl"], "error": r["error"]}
            for r in errors
        ],
        "kl_infinite_objectives": [
            {"run_id": r["run_id"], "impl": r["impl"],
             "detail": r["objective_status"]} for r in kl_inf
        ],
        "git_commit": subprocess.run(
            ["git", "rev-parse", "HEAD"], cwd=HERE, capture_output=True,
            text=True, shell=True).stdout.strip(),
    }
    meta_path = out_dir / ("metadata_smoke.json" if args.smoke else "metadata.json")
    meta_path.write_text(json.dumps(meta, indent=2) + "\n", encoding="utf-8")

    print(f"\nwrote {len(rows)} rows -> {csv_path}")
    print(f"error runs: {len(errors)}; kl_infinite objectives: {len(kl_inf)}")
    if cross:
        print(f"max library-vs-independent crosscheck rel diff: {max(cross):.3e} "
              f"(max abs diff: {max(cross_abs):.3e})")
    for r in errors:
        print(f"  ERROR {r['impl']} {r['run_id']}: {r['error']}")
    for r in kl_inf:
        print(f"  KL-INFINITE {r['impl']} {r['run_id']}: {r['objective_status']}")
    if cross_fail:
        print(f"FATAL: crosscheck mismatch beyond rel 1e-8 AND abs 1e-9: "
              f"{cross_fail}", file=sys.stderr)
        sys.exit(2)


if __name__ == "__main__":
    main()