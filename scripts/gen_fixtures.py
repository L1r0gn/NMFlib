"""Generate src/fixtures_test.mbt from measured sklearn reference values.

Implements the original PLAN sklearn-comparison requirement (PLAN.md, former
T15 section, deferred and executed as T16): Python generates >=3 fixed
datasets (including exact zeros / rank deficiency) with sklearn reference
objectives/errors as MoonBit literals; the MoonBit fixture tests fit NMFlib
with the SAME configuration and assert the objective/reconstruction error
are within tolerance of the reference (no element-wise W/H comparison).

The 5% assertion tolerance is NOT assumed: candidates are selected only
after the full experiment grid (validation/sklearn_reference/results/
results.csv) shows a measured seed-42 gap <= 3% (margin below 5%) on BOTH
the full objective and the reconstruction error, with reference magnitudes
large enough for a relative tolerance to be meaningful (J >= 1e-3,
recon >= 1e-2). Every measured gap, including excluded candidates, is
recorded in validation/sklearn_reference/results/fixtures_selection.json.

Usage (from repo root, after run_experiments.py):
  python scripts/gen_fixtures.py
"""

from __future__ import annotations

import csv
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VAL = ROOT / "validation" / "sklearn_reference"
sys.path.insert(0, str(VAL))

import numpy as np  # noqa: E402

from run_experiments import mbx_literal  # noqa: E402

FIXTURE_SEED = 42
MAX_ITER = 500
TOL = 1e-6
SELECT_GAP = 0.03
ASSERT_GAP = 0.05
MIN_J = 1e-3
MIN_RECON = 1e-2

SOLVER_MBT = {"MU": "@nmf.Solver::MU", "CD": "@nmf.Solver::CD"}
LOSS_MBT = {
    "frobenius": "@nmf.Loss::Frobenius",
    "kl": "@nmf.Loss::KLDivergence",
}


def load_grid():
    with (VAL / "results" / "results.csv").open(encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    idx = {}
    for r in rows:
        if r["init"] != "Random" or r["seed"] != str(FIXTURE_SEED):
            continue
        if r["status"] != "ok" or r["objective_status"] != "ok":
            continue
        key = (r["dataset"], r["solver"], r["loss"], r["reg_name"], r["impl"])
        idx[key] = r
    return idx


def main():
    idx = load_grid()
    meta = json.loads((VAL / "data" / "metadata.json").read_text(encoding="utf-8"))
    datasets = {}
    for name in meta:
        with np.load(VAL / "data" / f"{name}.npz") as z:
            datasets[name] = z["v"]

    candidates, selected = [], []
    for ds in sorted(datasets):
        for solver, loss in [("MU", "frobenius"), ("CD", "frobenius"), ("MU", "kl")]:
            for reg in ["none", "l1", "l2", "l1l2"]:
                key = (ds, solver, loss, reg)
                rn, rs = idx.get(key + ("nmflib",)), idx.get(key + ("sklearn",))
                if rn is None or rs is None:
                    continue
                jn, js = float(rn["full_objective"]), float(rs["full_objective"])
                cn, cs = float(rn["reconstruction_error"]), float(rs["reconstruction_error"])
                jgap = (jn - js) / js if js > 0 else float("inf")
                cgap = (cn - cs) / cs if cs > 0 else float("inf")
                reasons = []
                if js < MIN_J:
                    reasons.append(f"reference objective {js:.3g} < {MIN_J} (relative tolerance ill-conditioned near zero)")
                if cs < MIN_RECON:
                    reasons.append(f"reference recon {cs:.3g} < {MIN_RECON}")
                if abs(jgap) > SELECT_GAP:
                    reasons.append(f"measured objective gap {jgap:+.3%} exceeds {SELECT_GAP:.0%} selection margin")
                if abs(cgap) > SELECT_GAP:
                    reasons.append(f"measured recon gap {cgap:+.3%} exceeds {SELECT_GAP:.0%} selection margin")
                entry = dict(
                    dataset=ds, solver=solver, loss=loss, reg_name=reg,
                    seed=FIXTURE_SEED, j_nmflib=jn, j_sklearn=js,
                    recon_nmflib=cn, recon_sklearn=cs,
                    objective_gap=jgap, recon_gap=cgap,
                    included=not reasons, reasons=reasons,
                    l1_reg=float(rn["l1_reg"]), l2_reg=float(rn["l2_reg"]),
                    rank=int(rn["rank"]),
                )
                candidates.append(entry)
                if not reasons:
                    selected.append(entry)

    if len({e["dataset"] for e in selected}) < 3:
        print("FATAL: fewer than 3 datasets meet the empirical selection rule; "
              "inspect fixtures_selection.json", file=sys.stderr)
        sys.exit(1)

    # ---- emit MoonBit fixture tests ----
    lines = [
        "// Generated by scripts/gen_fixtures.py — do not edit by hand.",
        "// T16 (PLAN former T15): sklearn 1.7.2 reference objectives/errors as",
        "// literals. Same-config NMFlib fits must land within 5% (relative) of",
        "// the independently re-evaluated sklearn reference. Candidates were",
        "// selected ONLY where the measured seed-42 gap was <= 3% on both the",
        "// full objective and ||V-WH||_F, with reference magnitudes >= 1e-3 /",
        "// 1e-2 so the relative tolerance is well-conditioned. All measured",
        "// gaps (including excluded configs) are recorded in",
        "// validation/sklearn_reference/results/fixtures_selection.json.",
        "// No element-wise W/H comparison is performed (NMF is non-unique).",
        "",
    ]
    for e in selected:
        ds = e["dataset"]
        v = datasets[ds]
        m, n = v.shape
        k = e["rank"]
        flat = ", ".join(mbx_literal(x) for x in v.ravel())
        title = (f"T16 fixture: {ds} {e['solver']} {e['loss']} {e['reg_name']} "
                 f"seed{FIXTURE_SEED} within 5% of sklearn reference")
        lines += [
            "///|",
            f'test "{title}" {{',
            f"  // measured native gap: objective {e['objective_gap']:+.4%}, "
            f"recon {e['recon_gap']:+.4%}",
            f"  let v = mat({m}, {n}, [{flat}])",
            "  let model = @nmf.NMF::new(",
            "    @nmf.NMFConfig::new(",
            f"      n_components={k},",
            f"      solver={SOLVER_MBT[e['solver']]},",
            f"      loss={LOSS_MBT[e['loss']]},",
            "      init=@nmf.Init::Random,",
            f"      max_iter={MAX_ITER},",
            f"      tol={mbx_literal(TOL)},",
            f"      seed={FIXTURE_SEED}UL,",
            f"      l1_reg={mbx_literal(e['l1_reg'])},",
            f"      l2_reg={mbx_literal(e['l2_reg'])},",
            "    ),",
            "  )",
            "  match model.fit(v) {",
            "    Ok(_) => ()",
            '    Err(e) => abort("fixture fit failed: \\{e}")',
            "  }",
            "  let w = unwrap_matrix(model.w())",
            "  let h = unwrap_matrix(model.h())",
            f"  assert_eq(w.rows(), {m})",
            f"  assert_eq(w.cols(), {k})",
            f"  assert_eq(h.rows(), {k})",
            f"  assert_eq(h.cols(), {n})",
            "  for i in 0..<w.rows() {",
            "    for j in 0..<w.cols() {",
            "      let x = unwrap_double(w.get(i, j))",
            "      assert_true(x >= 0.0 && x < inf())",
            "    }",
            "  }",
            "  for i in 0..<h.rows() {",
            "    for j in 0..<h.cols() {",
            "      let x = unwrap_double(h.get(i, j))",
            "      assert_true(x >= 0.0 && x < inf())",
            "    }",
            "  }",
            "  let j = unwrap_double(model.loss_value())",
            f"  let ref_j = {mbx_literal(e['j_sklearn'])}",
            f"  assert_true((j - ref_j).abs() / ref_j <= {ASSERT_GAP})",
            "  let rec = unwrap_double(model.reconstruction_error(v))",
            f"  let ref_rec = {mbx_literal(e['recon_sklearn'])}",
            f"  assert_true((rec - ref_rec).abs() / ref_rec <= {ASSERT_GAP})",
            "}",
            "",
        ]
    out = ROOT / "src" / "fixtures_test.mbt"
    out.write_text("\n".join(lines), encoding="utf-8")

    report = {
        "reference": "scikit-learn 1.7.2, independently re-evaluated objectives",
        "config": {"seed": FIXTURE_SEED, "max_iter": MAX_ITER, "tol": TOL,
                   "init": "Random"},
        "selection_rule": {
            "max_measured_gap": SELECT_GAP, "asserted_tolerance": ASSERT_GAP,
            "min_reference_objective": MIN_J, "min_reference_recon": MIN_RECON,
        },
        "selected": len(selected),
        "candidates": candidates,
    }
    report_path = VAL / "results" / "fixtures_selection.json"
    report_path.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print(f"selected {len(selected)}/{len(candidates)} fixture configs "
          f"across {len({e['dataset'] for e in selected})} datasets")
    for e in selected:
        print(f"  {e['dataset']} {e['solver']}-{e['loss']} {e['reg_name']}: "
              f"J gap {e['objective_gap']:+.4%}, recon gap {e['recon_gap']:+.4%}")
    print(f"wrote {out}")
    print(f"wrote {report_path}")


if __name__ == "__main__":
    main()